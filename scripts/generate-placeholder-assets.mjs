const SVG_DIRS = ['cards', 'enemies', 'fields'];

async function listSvgFiles(directory) {
  try {
    const entries = await readdir(directory, { withFileTypes: true });
    return entries
      .filter((entry) => entry.isFile() && entry.name.endsWith('.svg'))
      .map((entry) => entry.name)
      .sort();
  } catch (error) {
    if (error.code === 'ENOENT') {
      return [];
    }
    throw error;
  }
}

async function writeOutputs(files) {
  await mkdir(publicAssetsDir, { recursive: true });

  const expectedNames = new Map(SVG_DIRS.map((directory) => [directory, new Set()]));

  for (const [relativePath, content] of files) {
    const target = path.join(publicAssetsDir, relativePath);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, content, 'utf8');

    const [directory, name] = relativePath.split('/');
    if (directory !== undefined && name !== undefined && expectedNames.has(directory)) {
      expectedNames.get(directory).add(name);
    }
  }

  // Remove stale placeholders so the directory holds exactly the manifest set.
  for (const directory of SVG_DIRS) {
    const expected = expectedNames.get(directory);
    const existing = await listSvgFiles(path.join(publicAssetsDir, directory));

    for (const name of existing) {
      if (expected !== undefined && !expected.has(name)) {
        await rm(path.join(publicAssetsDir, directory, name));
        console.log(`removed stale public/assets/${directory}/${name}`);
      }
    }
  }

  const svgCount = [...files.keys()].filter((key) => key.endsWith('.svg')).length;
  console.log(`wrote ${svgCount} SVG placeholders under public/assets`);
  console.log(`wrote public/assets/${manifestName}`);
}

async function readIfExists(target) {
  try {
    return await readFile(target);
  } catch (error) {
    if (error.code === 'ENOENT') {
      return null;
    }
    throw error;
  }
}

async function checkOutputs(files) {
  const problems = [];

  for (const [relativePath, content] of files) {
    const actual = await readIfExists(path.join(publicAssetsDir, relativePath));

    if (actual === null) {
      problems.push(`missing public/assets/${relativePath}`);
    } else if (!actual.equals(Buffer.from(content, 'utf8'))) {
      problems.push(`changed public/assets/${relativePath}`);
    }
  }

  for (const directory of SVG_DIRS) {
    const expected = new Set(
      [...files.keys()]
        .filter((key) => key.startsWith(`${directory}/`))
        .map((key) => key.slice(directory.length + 1)),
    );

    for (const name of await listSvgFiles(path.join(publicAssetsDir, directory))) {
      if (!expected.has(name)) {
        problems.push(`unexpected public/assets/${directory}/${name}`);
      }
    }
  }

  if (problems.length > 0) {
    console.error('Placeholder assets are out of date:');
    for (const problem of problems) {
      console.error(`  ${problem}`);
    }
    console.error('Run: node scripts/generate-placeholder-assets.mjs');
    process.exitCode = 1;
    return false;
  }

  const svgCount = [...files.keys()].filter((key) => key.endsWith('.svg')).length;
  console.log(
    `verified ${svgCount} SVG placeholders and public/assets/${manifestName} are byte-identical to generator output`,
  );
  return true;
}

async function main() {
  const cards = await readCatalog('cards.json');
  const enemies = await readCatalog('enemies.json');
  const { files } = buildOutputs(cards, enemies);

  if (process.argv.includes('--check')) {
    await checkOutputs(files);
    return;
  }

  await writeOutputs(files);
}

main().catch((error) => {
  console.error(`generate-placeholder-assets: ${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 1;
});
