/** Deterministic integer coordinate; avoids `-0`. */
function n(value) {
  const rounded = Math.round(value);
  return rounded === 0 ? 0 : rounded;
}

function escapeXml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;');
}

function openSvg(width, height, title) {
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Generated by scripts/generate-placeholder-assets.mjs. Do not edit by hand: replace this file at its manifest path. -->',
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-labelledby="title">`,
    `  <title id="title">${escapeXml(title)}</title>`,
  ];
}

function textLine(x, y, size, fill, value, extra = '') {
  return `  <text x="${n(x)}" y="${n(y)}" text-anchor="middle" font-family="sans-serif" font-size="${size}" fill="${fill}"${extra}>${escapeXml(value)}</text>`;
}

/** The element glyph: one distinct geometric mark per element. */
function elementGlyph(element, cx, cy, r, accent) {
  const stroke = Math.max(4, n(r * 0.07));

  switch (element) {
    case 'ember':
      return [
        `  <polygon points="${n(cx)},${n(cy - r)} ${n(cx + r * 0.78)},${n(cy + r * 0.72)} ${n(cx - r * 0.78)},${n(cy + r * 0.72)}" fill="none" stroke="${accent}" stroke-width="${stroke}" stroke-linejoin="round"/>`,
        `  <polygon points="${n(cx)},${n(cy - r * 0.36)} ${n(cx + r * 0.3)},${n(cy + r * 0.44)} ${n(cx - r * 0.3)},${n(cy + r * 0.44)}" fill="${accent}"/>`,
      ].join('\n');
    case 'frost':
      return [
        `  <line x1="${n(cx - r)}" y1="${n(cy)}" x2="${n(cx + r)}" y2="${n(cy)}" stroke="${accent}" stroke-width="${stroke}" stroke-linecap="round"/>`,
        `  <line x1="${n(cx - r * 0.5)}" y1="${n(cy - r * 0.87)}" x2="${n(cx + r * 0.5)}" y2="${n(cy + r * 0.87)}" stroke="${accent}" stroke-width="${stroke}" stroke-linecap="round"/>`,
        `  <line x1="${n(cx - r * 0.5)}" y1="${n(cy + r * 0.87)}" x2="${n(cx + r * 0.5)}" y2="${n(cy - r * 0.87)}" stroke="${accent}" stroke-width="${stroke}" stroke-linecap="round"/>`,
        `  <circle cx="${n(cx)}" cy="${n(cy)}" r="${n(r * 0.2)}" fill="${accent}"/>`,
      ].join('\n');
    case 'gale':
      return [
        `  <path d="M ${n(cx - r)} ${n(cy - r * 0.55)} Q ${n(cx)} ${n(cy - r * 1.05)} ${n(cx + r)} ${n(cy - r * 0.55)}" fill="none" stroke="${accent}" stroke-width="${stroke}" stroke-linecap="round"/>`,
        `  <path d="M ${n(cx - r * 0.8)} ${n(cy)} Q ${n(cx)} ${n(cy - r * 0.5)} ${n(cx + r * 0.8)} ${n(cy)}" fill="none" stroke="${accent}" stroke-width="${stroke}" stroke-linecap="round"/>`,
        `  <path d="M ${n(cx - r * 0.6)} ${n(cy + r * 0.55)} Q ${n(cx)} ${n(cy + r * 0.05)} ${n(cx + r * 0.6)} ${n(cy + r * 0.55)}" fill="none" stroke="${accent}" stroke-width="${stroke}" stroke-linecap="round"/>`,
      ].join('\n');
    case 'stone':
      return [
        `  <rect x="${n(cx - r * 0.7)}" y="${n(cy - r * 0.7)}" width="${n(r * 1.4)}" height="${n(r * 1.4)}" transform="rotate(45 ${n(cx)} ${n(cy)})" fill="none" stroke="${accent}" stroke-width="${stroke}"/>`,
        `  <rect x="${n(cx - r * 0.32)}" y="${n(cy - r * 0.32)}" width="${n(r * 0.64)}" height="${n(r * 0.64)}" transform="rotate(45 ${n(cx)} ${n(cy)})" fill="${accent}"/>`,
      ].join('\n');
    default:
      return [
        `  <circle cx="${n(cx)}" cy="${n(cy)}" r="${n(r * 0.9)}" fill="none" stroke="${accent}" stroke-width="${stroke}"/>`,
        `  <circle cx="${n(cx)}" cy="${n(cy)}" r="${n(r * 0.5)}" fill="none" stroke="${accent}" stroke-width="${stroke}"/>`,
        `  <circle cx="${n(cx)}" cy="${n(cy)}" r="${n(r * 0.14)}" fill="${accent}"/>`,
      ].join('\n');
  }
}

/** Card type mark, drawn inside the card art box. */
function typeGlyph(type, cx, cy, r, accent) {
  const stroke = Math.max(4, n(r * 0.09));

  switch (type) {
    case 'attack':
      return [
        `  <polygon points="${n(cx)},${n(cy - r)} ${n(cx + r * 0.72)},${n(cy)} ${n(cx)},${n(cy + r)} ${n(cx - r * 0.72)},${n(cy)}" fill="none" stroke="${accent}" stroke-width="${stroke}" stroke-linejoin="round"/>`,
        `  <polygon points="${n(cx)},${n(cy - r * 0.4)} ${n(cx + r * 0.29)},${n(cy)} ${n(cx)},${n(cy + r * 0.4)} ${n(cx - r * 0.29)},${n(cy)}" fill="${accent}"/>`,
      ].join('\n');
    case 'ward':
      return [
        `  <path d="M ${n(cx)} ${n(cy - r)} L ${n(cx + r * 0.8)} ${n(cy - r * 0.55)} L ${n(cx + r * 0.58)} ${n(cy + r * 0.45)} L ${n(cx)} ${n(cy + r)} L ${n(cx - r * 0.58)} ${n(cy + r * 0.45)} L ${n(cx - r * 0.8)} ${n(cy - r * 0.55)} Z" fill="none" stroke="${accent}" stroke-width="${stroke}" stroke-linejoin="round"/>`,
        `  <line x1="${n(cx)}" y1="${n(cy - r * 0.5)}" x2="${n(cx)}" y2="${n(cy + r * 0.5)}" stroke="${accent}" stroke-width="${stroke}" stroke-linecap="round"/>`,
      ].join('\n');
    case 'utility':
      return [
        `  <circle cx="${n(cx)}" cy="${n(cy)}" r="${n(r * 0.72)}" fill="none" stroke="${accent}" stroke-width="${stroke}"/>`,
        `  <circle cx="${n(cx)}" cy="${n(cy)}" r="${n(r * 0.26)}" fill="${accent}"/>`,
      ].join('\n');
    default:
      return [
        `  <polygon points="${n(cx)},${n(cy - r)} ${n(cx + r * 0.28)},${n(cy - r * 0.28)} ${n(cx + r)},${n(cy)} ${n(cx + r * 0.28)},${n(cy + r * 0.28)} ${n(cx)},${n(cy + r)} ${n(cx - r * 0.28)},${n(cy + r * 0.28)} ${n(cx - r)},${n(cy)} ${n(cx - r * 0.28)},${n(cy - r * 0.28)}" fill="none" stroke="${accent}" stroke-width="${stroke}" stroke-linejoin="round"/>`,
        `  <circle cx="${n(cx)}" cy="${n(cy)}" r="${n(r * 0.2)}" fill="${accent}"/>`,
      ].join('\n');
  }
}

/** A short, data-derived effect summary for the placeholder text band. */
function effectSummary(card) {
  const parts = [];

  if (card.damage !== undefined) {
    parts.push(`Deal ${card.damage} damage${card.piercing === true ? ' (piercing)' : ''}`);
  }

  if (card.defense !== undefined) {
    parts.push(`Gain ${card.defense} defense`);
  }

  if (card.draw !== undefined) {
    parts.push(`Draw ${card.draw}`);
  }

  if (card.energy !== undefined) {
    parts.push(`Gain ${card.energy} energy`);
  }

  if (card.status !== undefined) {
    parts.push(
      `${card.status.kind[0].toUpperCase()}${card.status.kind.slice(1)} ${card.status.stacks} on ${card.status.target}`,
    );
  }

  if (card.heal !== undefined) {
    parts.push(`Heal ${card.heal}`);
  }

  if (card.shiftTo !== undefined) {
    parts.push(`Set field to ${ELEMENT_LABEL[card.shiftTo]}`);
  }

  if (card.fieldBonus !== undefined) {
    const bonus = [];
    if (card.fieldBonus.damage !== undefined) {
      bonus.push(`+${card.fieldBonus.damage} damage`);
    }
    if (card.fieldBonus.defense !== undefined) {
      bonus.push(`+${card.fieldBonus.defense} defense`);
    }
    if (bonus.length > 0) {
      parts.push(`${bonus.join(' ')} while ${ELEMENT_LABEL[card.element]} is active`);
    }
  }

  return parts.length > 0 ? parts.join(' / ') : TYPE_LABEL[card.type];
}

function wrapText(value, maxChars) {
  const words = String(value).split(' ');
  const lines = [];
  let current = '';

  for (const word of words) {
    const candidate = current === '' ? word : `${current} ${word}`;

    if (candidate.length > maxChars && current !== '') {
      lines.push(current);
      current = word;
    } else {
      current = candidate;
    }
  }

  if (current !== '') {
    lines.push(current);
  }

  return lines;
}

function titleFontSize(name) {
  const size = Math.floor(200 / (name.length * 0.62));
  return Math.max(14, Math.min(22, size));
}

