#!/usr/bin/env node
/**
 * Fieldbound placeholder asset generator (CNT-FR-05, VIS-CON-06).
 *
 * Reads the frozen card and enemy catalogs, writes exactly one deterministic
 * SVG per card, enemy and field under `public/assets/`, and rewrites
 * `public/assets/assets.manifest.json` - the only mapping from content ids to
 * files.
 *
 * Contract:
 *  - 32 card SVGs, 4 enemy SVGs and 5 field SVGs (41 files total);
 *  - every file begins with the generated banner and uses LF line endings;
 *  - output contains no timestamp, random value, absolute path or
 *    locale-dependent formatting, so two runs are byte-identical;
 *  - `--check` compares the generated bytes with what is on disk and exits
 *    non-zero on any missing, extra or different file without writing.
 *
 * The script is data-only presentation: it renders ids, names, elements, costs,
 * health and effect descriptors from the catalogs. It never implements damage,
 * draw, status or affordability rules (VIS-CON-08).
 */
import { readFile, readdir, rm, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');
const contentDir = path.join(repoRoot, 'src', 'content');
const publicAssetsDir = path.join(repoRoot, 'public', 'assets');
const manifestName = 'assets.manifest.json';

/** Fields in canonical order; mirrors `ELEMENTS` in `src/engine/types.ts`. */
const FIELD_ELEMENTS = ['ember', 'frost', 'gale', 'stone', 'neutral'];

const ELEMENT_LABEL = {
  ember: 'Ember',
  frost: 'Frost',
  gale: 'Gale',
  stone: 'Stone',
  neutral: 'Neutral',
};

const TYPE_LABEL = {
  attack: 'Attack',
  ward: 'Ward',
  utility: 'Utility',
  shift: 'Shift',
};

/**
 * Element palette shared with `docs/ASSET-SPEC.md`. Values are plain hex so
 * placeholders stay same-origin and dependency-free.
 */
const PALETTE = {
  ember: { base: '#7f1d1d', accent: '#f59e0b', ink: '#fff7ed', shade: '#450a0a' },
  frost: { base: '#1e3a8a', accent: '#a5f3fc', ink: '#eff6ff', shade: '#172554' },
  gale: { base: '#115e59', accent: '#a7f3d0', ink: '#ecfdf5', shade: '#042f2e' },
  stone: { base: '#5b4636', accent: '#d6b98c', ink: '#fdf6e3', shade: '#2f241b' },
  neutral: { base: '#374151', accent: '#e5e7eb', ink: '#f9fafb', shade: '#111827' },
};

/**
 * The published spec block. Card metadata is documented in
 * `docs/features/card-content.md` section 4.5.
 */
const SPEC = {
  card: {
    width: 300,
    height: 420,
    format: 'svg',
    safeArea: 24,
    titleBand: 72,
    artBox: [240, 200],
    textBand: 96,
  },
  enemy: { width: 512, height: 512, format: 'svg', safeArea: 32 },
  field: { width: 256, height: 256, format: 'svg', safeArea: 16 },
};

const FILE_PATTERN = {
  card: (entry) => `cards/${entry.id}.svg`,
  enemy: (entry) => `enemies/${entry.id}.svg`,
  field: (entry) => `fields/field-${entry.element}.svg`,
};

