function renderFieldSvg(element) {
  const palette = PALETTE[element];
  const label = ELEMENT_LABEL[element];
  const lines = openSvg(
    SPEC.field.width,
    SPEC.field.height,
    `${label} Field`,
  );

  lines.push(`  <rect x="0" y="0" width="256" height="256" rx="24" fill="${palette.base}"/>`);
  lines.push(
    `  <rect x="10" y="10" width="236" height="236" rx="16" fill="none" stroke="${palette.accent}" stroke-width="3"/>`,
  );
  lines.push(
    `  <text x="128" y="48" text-anchor="middle" font-family="sans-serif" font-size="12" letter-spacing="3" fill="${palette.accent}">FIELD</text>`,
  );
  lines.push(elementGlyph(element, 128, 112, 58, palette.accent));
  lines.push(textLine(128, 216, 24, palette.ink, label, ' font-weight="700"'));
  lines.push('</svg>');

  return `${lines.join('\n')}\n`;
}

