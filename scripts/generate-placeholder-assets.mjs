function renderCardSvg(card) {
  const palette = PALETTE[card.element];
  const lines = openSvg(
    SPEC.card.width,
    SPEC.card.height,
    `${card.name} - ${ELEMENT_LABEL[card.element]} ${TYPE_LABEL[card.type]}`,
  );

  lines.push(`  <rect x="0" y="0" width="300" height="420" rx="20" fill="${palette.base}"/>`);
  lines.push(
    `  <rect x="12" y="12" width="276" height="396" rx="16" fill="none" stroke="${palette.accent}" stroke-width="3"/>`,
  );
  lines.push(`  <line x1="24" y1="94" x2="276" y2="94" stroke="${palette.accent}" stroke-width="2"/>`);
  lines.push(`  <circle cx="46" cy="58" r="18" fill="${palette.accent}"/>`);
  lines.push(
    `  <text x="46" y="65" text-anchor="middle" font-family="sans-serif" font-size="20" font-weight="700" fill="${palette.shade}">${card.cost}</text>`,
  );
  lines.push(
    `  <text x="174" y="65" text-anchor="middle" font-family="sans-serif" font-size="${titleFontSize(card.name)}" font-weight="700" fill="${palette.ink}">${escapeXml(card.name)}</text>`,
  );
  lines.push(
    `  <rect x="30" y="96" width="240" height="200" rx="14" fill="${palette.shade}" fill-opacity="0.45" stroke="${palette.accent}" stroke-width="2"/>`,
  );
  lines.push(typeGlyph(card.type, 150, 196, 64, palette.accent));

  const effectLines = wrapText(effectSummary(card), 30).slice(0, 3);
  effectLines.forEach((line, index) => {
    lines.push(textLine(150, 318 + index * 18, 14, palette.ink, line));
  });

  lines.push(
    textLine(
      150,
      380,
      13,
      palette.accent,
      `${ELEMENT_LABEL[card.element].toUpperCase()} / ${TYPE_LABEL[card.type].toUpperCase()}`,
      ' letter-spacing="1.2"',
    ),
  );
  lines.push('</svg>');

  return `${lines.join('\n')}\n`;
}

