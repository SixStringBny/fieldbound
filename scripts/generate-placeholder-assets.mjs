async function readCatalog(name) {
  const raw = await readFile(path.join(contentDir, name), 'utf8');
  const parsed = JSON.parse(raw);

  if (!Array.isArray(parsed)) {
    throw new Error(`${name} must contain a JSON array`);
  }

  return parsed;
}

function requireString(value, label) {
  if (typeof value !== 'string' || value.length === 0) {
    throw new Error(`${label} must be a non-empty string`);
  }

  return value;
}

function requireElement(value, label) {
  if (typeof value !== 'string' || !(value in PALETTE)) {
    throw new Error(`${label} has unsupported element "${String(value)}"`);
  }

  return value;
}

/**
 * Builds every generated file in memory. Pure over the catalogs, so `--check`
 * compares exactly the bytes a write would produce.
 */
function buildOutputs(cards, enemies) {
  const files = new Map();
  const assets = [];

  for (const card of cards) {
    const id = requireString(card.id, 'card id');
    const element = requireElement(card.element, `card "${id}"`);

    if (!(card.type in TYPE_LABEL)) {
      throw new Error(`card "${id}" has unsupported type "${String(card.type)}"`);
    }

    const entry = {
      id: `card:${id}`,
      kind: 'card',
      element,
      name: requireString(card.name, `card "${id}" name`),
      path: FILE_PATTERN.card({ id }),
      width: SPEC.card.width,
      height: SPEC.card.height,
      format: SPEC.card.format,
      safeArea: SPEC.card.safeArea,
    };

    assets.push(entry);
    files.set(entry.path, renderCardSvg(card));
  }

  for (const enemy of enemies) {
    const id = requireString(enemy.id, 'enemy id');
    const element = requireElement(enemy.element, `enemy "${id}"`);

    if (!Number.isInteger(enemy.maxHealth) || enemy.maxHealth <= 0) {
      throw new Error(`enemy "${id}" must have a positive integer maxHealth`);
    }

    const entry = {
      id: `enemy:${id}`,
      kind: 'enemy',
      element,
      name: requireString(enemy.name, `enemy "${id}" name`),
      path: FILE_PATTERN.enemy({ id }),
      width: SPEC.enemy.width,
      height: SPEC.enemy.height,
      format: SPEC.enemy.format,
      safeArea: SPEC.enemy.safeArea,
    };

    assets.push(entry);
    files.set(entry.path, renderEnemySvg(enemy));
  }

  for (const element of FIELD_ELEMENTS) {
    const entry = {
      id: `field:${element}`,
      kind: 'field',
      element,
      name: `${ELEMENT_LABEL[element]} Field`,
      path: FILE_PATTERN.field({ element }),
      width: SPEC.field.width,
      height: SPEC.field.height,
      format: SPEC.field.format,
      safeArea: SPEC.field.safeArea,
    };

    assets.push(entry);
    files.set(entry.path, renderFieldSvg(element));
  }

  const ids = new Set();
  const paths = new Set();

  for (const entry of assets) {
    if (ids.has(entry.id)) {
      throw new Error(`duplicate asset id "${entry.id}"`);
    }
    if (paths.has(entry.path)) {
      throw new Error(`duplicate asset path "${entry.path}"`);
    }
    ids.add(entry.id);
    paths.add(entry.path);
  }

  // Sort by key with a plain code-unit comparison: `localeCompare` is
  // locale-dependent and would break byte-identical output across machines.
  assets.sort((left, right) => (left.id < right.id ? -1 : left.id > right.id ? 1 : 0));

  const manifest = {
    version: 1,
    generatedBy: 'scripts/generate-placeholder-assets.mjs',
    spec: SPEC,
    assets,
  };

  files.set(manifestName, `${JSON.stringify(manifest, null, 2)}\n`);

  return { files, manifest };
}

